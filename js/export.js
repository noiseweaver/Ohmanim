// Background music, laid under the whole video once the scene has finished playing.
const MUSIC_HELPERS = `

def _music(scene, name, gain=-10.0, duck=-9.0, fade=2.0):
    """Loop a music bed under the whole video at gain dB, duck dB quieter while narration
    plays, fading out over the last fade seconds. Call it at the end of construct()."""
    end = scene.renderer.time
    try:
        import manimweb  # rendering in Ohmanim: the browser mixes it
        return manimweb.music(name, gain, duck, fade, end, _VOICED)
    except ImportError:
        pass
    from pydub import AudioSegment
    bed = AudioSegment.from_file(str(_VHERE / name))
    ms = int(end * 1000)
    if not len(bed) or ms <= 0:
        return
    bed = (bed * (ms // len(bed) + 1))[:ms]
    spans = []
    for t, n in sorted(_VOICED):
        a = int(t * 1000)
        b = a + len(AudioSegment.from_file(str(_VHERE / n)))
        if spans and a <= spans[-1][1] + 600:
            spans[-1][1] = max(spans[-1][1], b)
        else:
            spans.append([a, b])
    if duck:
        for a, b in spans:
            bed = bed.fade(to_gain=duck, start=max(0, a - 300), end=max(1, a))
            if b < ms:
                bed = bed.fade(to_gain=-duck, start=b, end=min(ms, b + 300))
    bed = bed.apply_gain(gain).fade_out(min(ms, int(fade * 1000)))
    scene.renderer.file_writer.add_audio_segment(bed, time=0)
`;

// Captions go next to the video as WebVTT and SRT, timed from where each clip starts.
const CAPTION_HELPERS = `

def _write_captions(name):
    """Write the narration captions as name.vtt and name.srt next to this file."""
    def ts(t, sep):
        ms = int(round(t * 1000))
        h, ms = divmod(ms, 3600000)
        m, ms = divmod(ms, 60000)
        s, ms = divmod(ms, 1000)
        return f"{h:02}:{m:02}:{s:02}{sep}{ms:03}"
    esc = lambda s: s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    vtt, srt = ["WEBVTT", ""], []
    for i, (a, b, s) in enumerate(_CAPS, 1):
        vtt += [f"{ts(a, '.')} --> {ts(b, '.')}", esc(s), ""]
        srt += [str(i), f"{ts(a, ',')} --> {ts(b, ',')}", s, ""]
    try:
        (_VHERE / f"{name}.vtt").write_text("\\n".join(vtt), encoding="utf-8")
        (_VHERE / f"{name}.srt").write_text("\\n".join(srt), encoding="utf-8")
    except OSError as e:
        print("Could not write captions:", e)
`;

// Split a caption into cues of at most two 42-character lines, timed by length across the clip.
export function captionCues(text, dur) {
  const words = String(text || '').replace(/\s+/g, ' ').trim().split(' ').filter(Boolean);
  if (!words.length || !(dur > 0)) return [];
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line && (line + ' ' + w).length > 42) { lines.push(line); line = w; } else line = line ? line + ' ' + w : w;
    // A sentence end is a good place to start a new line.
    if (/[.!?]$/.test(line) && line.length > 20) { lines.push(line); line = ''; }
  }
  if (line) lines.push(line);
  const cues = [];
  for (let i = 0; i < lines.length; i += 2) cues.push(lines.slice(i, i + 2).join('\n'));
  const total = cues.reduce((t, c) => t + c.length, 0);
  let t = 0;
  return cues.map((c, i) => {
    const a = t;
    t = i === cues.length - 1 ? dur : t + (dur * c.length) / total;
    return [Math.round(a * 1000) / 1000, Math.round(t * 1000) / 1000, c];
  });
}

// Volume (0..1) as Manim's gain in decibels.
const dB = (v) => 20 * Math.log10(Math.max(0.001, v));
// Soundtracks of the clips that start on this click, as {asset, vol}.
const clipSounds = (project, beat) => beat.phases.flat().filter((a) => a.kind === 'enter').flatMap((a) => videosIn(a.obj))
  .filter((o) => project.assets?.[o.asset]?.hasAudio && (o.vol ?? 1) > 0).map((o) => ({ asset: o.asset, vol: o.vol ?? 1 }));
// A click's sound effects whose files are in the lesson, and not silenced.
const soundsOf = (project, beat) => (beat.sounds || []).filter((sd) => sd.asset && project.assets?.[sd.asset] && (sd.vol ?? 1) > 0);

export function exportPython(project, { mode = 'slides' } = {}) {
  fonts.lesson = project.font || DEFAULT_FONT;
  pyAssets = project.assets || {};
  const cls = ident(project.title);
  const beats = timeline(project);
  const L = [];
  const w = (s = '', ind = 2) => L.push(s ? '    '.repeat(ind) + s : '');
  L.push(`"""${String(project.title || 'Lesson').replace(/"""/g, "'''")} — generated by Ohmanim.`);
  L.push('');
  if (mode === 'slides') {
    L.push('Render and present:');
    L.push(`    manim-slides render lesson.py ${cls}`);
    L.push(`    manim-slides ${cls}                      # present`);
    L.push(`    manim-slides convert ${cls} lesson.html   # self-contained HTML slideshow`);
  } else {
    L.push('Render a video:');
    L.push(`    manim -qh lesson.py ${cls}`);
  }
  if (project.slides.some((s) => s.objects.some((o) => o.type === 'math'))) L.push('\nMath objects use MathTex and need a LaTeX installation.');
  const media = usedAssets(project).flatMap((id) => { const a = project.assets[id]; return a.kind === 'video' && a.hasAudio ? [mediaFile(id, a), clipSoundFile(id)] : [mediaFile(id, a)]; });
  if (media.length) L.push(`\nPut these files next to this file (Download media in Ohmanim): ${media.join(', ')}`);
  const voiced = beats.some((b) => b.voice && project.assets?.[b.voice]);
  const music = project.music?.asset && project.assets?.[project.music.asset] ? project.music : null;
  const audible = voiced || !!music || beats.some((b) => soundsOf(project, b).length || clipSounds(project, b).length);
  if (audible) L.push('Sound uses self.add_sound; rendering it on a computer needs ffmpeg.');
  const captioned = beats.some((b) => b.caption && b.voice && project.assets?.[b.voice]);
  if (captioned) L.push(`Captions are written next to this file as ${cls}.vtt and ${cls}.srt, timed to the video.`);
  // Backgrounds: a plain colour shared by every slide is just the camera colour. Anything
  // else is a full-frame Group behind everything, cross-faded when a slide changes it.
  const bgs = project.slides.map((s) => bgOf(project, s));
  const keys = bgs.map(bgKey);
  const fancy = !(keys.every((k) => k === keys[0]) && isPlain(bgs[0]));
  L.push('"""');
  L.push('from manim import *');
  if (mode === 'slides') L.push('from manim_slides import Slide');
  L.push(HELPERS);
  if (fancy) L.push(BG_HELPERS);
  const pictured = project.slides.some((s) => s.objects.some(hasImage));
  if (pictured) L.push(IMAGE_HELPERS);
  if (project.slides.some((s) => s.objects.some(hasVideo))) L.push(VIDEO_HELPERS);
  if (audible) L.push(AUDIO_HELPERS);
  if (music) L.push(MUSIC_HELPERS);
  if (captioned) L.push(CAPTION_HELPERS);
  L.push('');
  L.push(`class ${cls}(${mode === 'slides' ? 'Slide' : 'Scene'}):`);
  w('def construct(self):', 1);
  w(`self.camera.background_color = ManimColor(${str(bgs[0].fill === 'radial' ? bgs[0].color2 : bgs[0].color)})`);
  w('M = {}');
  let bgVar = null, bgAt = null, nbg = 0;
  if (fancy) { bgVar = `_bg${nbg++}`; bgAt = keys[0]; w(`${bgVar} = ${bgPy(bgs[0], project)}`); w(`self.add(${bgVar})`); }
  if (mode !== 'slides') w('self.next_slide = lambda notes="": self.wait(1)');
  let lastSlide = -1, tmp = 0;
  beats.forEach((beat, bi) => {
    const slide = project.slides[beat.slide];
    if (beat.slide !== lastSlide) {
      w('');
      w(`# ---- Slide ${beat.slide + 1}: ${String(slide.name || '').replace(/\n/g, ' ')}`);
      lastSlide = beat.slide;
    }
    if (bi > 0) {
      const notes = beat.first && slide.notes ? `notes=${str(slide.notes)}` : '';
      w(`self.next_slide(${notes})`);
    } else if (mode === 'slides' && slide.notes) {
      w(`# notes: ${slide.notes.replace(/\n/g, ' ')}`);
    }
    if (fancy && keys[beat.slide] !== bgAt) {
      // Fade the new background in over the old one. Objects already on screen join the
      // animation so they stay drawn on top of it.
      const v = `_bg${nbg++}`;
      w(`${v} = ${bgPy(bgs[beat.slide], project)}`);
      w(`self.play(FadeIn(${v}), *[Animation(m) for m in M.values()], run_time=0.8)`);
      w(`self.remove(${bgVar})`);
      bgVar = v; bgAt = keys[beat.slide];
    }
    const clip = beat.voice && project.assets?.[beat.voice];
    // A click lasts as long as its animations, its narration and its hold time, whichever is longest.
    const len = Math.max(beat.hold || 0, clip ? clip.dur : 0, beat.clip || 0);
    if (len > 0) w('_click = self.renderer.time');
    if (clip) {
      const caps = captionCues(beat.caption, clip.dur).map(([a, b, t]) => `(${n(a)}, ${n(b)}, ${str(t)})`);
      w(`_say(self, ${str(mediaFile(beat.voice, clip))}${caps.length ? `, [${caps.join(', ')}]` : ''})`);
    }
    for (const sd of clipSounds(project, beat)) w(`_sfx(self, ${str(clipSoundFile(sd.asset))}${sd.vol < 1 ? `, ${n(dB(sd.vol))}` : ''})`);
    for (const sd of soundsOf(project, beat)) w(`_sfx(self, ${str(mediaFile(sd.asset, project.assets[sd.asset]))}${sd.vol < 1 ? `, ${n(dB(sd.vol))}` : ''})`);
    for (const phase of beat.phases) {
      const anims = [], after = [], adds = [];
      for (const a of phase) {
        const ref = `M[${str(a.id)}]`;
        if (a.kind === 'transform') {
          const v = `_t${tmp++}`;
          w(`${v} = ${objectPy(a.to)}`);
          anims.push(`ReplacementTransform(${ref}, ${v})`);
          after.push(`${ref} = ${v}`);
        } else if (a.kind === 'fadeout') {
          anims.push(`FadeOut(${ref})`);
          after.push(`del ${ref}`);
        } else if (a.kind === 'enter') {
          w(`${ref} = ${objectPy(a.obj)}`);
          const anim = DRAWN.includes(a.anim) && hasImage(a.obj) ? 'FadeIn' : a.anim;
          // A clip keeps playing while it fades or grows in.
          if (ENTER[anim]) anims.push(hasVideo(a.obj) ? ENTER[anim](ref).replace(/\)$/, ', suspend_mobject_updating=False)') : ENTER[anim](ref)); else adds.push(ref);
        } else if (a.kind === 'emph' && EMPH[a.anim]) {
          const o = a.obj || project.slides[beat.slide].objects.find((q) => q.id === a.id);
          anims.push(a.anim === 'Indicate' && o && hasImage(o) ? `_pulse(${ref})` : EMPH[a.anim](ref));
        }
      }
      if (adds.length) w(`self.add(${adds.join(', ')})`);
      if (anims.length) w(`self.play(${anims.join(', ')})`);
      after.forEach((s) => w(s));
    }
    if (len > 0) w(`_hold(self, _click, ${n(len)})`);
  });
  w('');
  if (captioned) w(`_write_captions(${str(cls)})`);
  w('self.next_slide()');
  if (music) w(`_music(self, ${str(mediaFile(music.asset, project.assets[music.asset]))}, ${n(dB(music.vol ?? 0.3))}, ${n(music.duck ? dB(music.duck) : 0)})`);
  return L.join('\n') + '\n';
}
