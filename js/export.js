// Generates a Manim Community script from a project. Geometry comes from the
// same primitives the editor draws, so the render matches the preview.
import { REG, exprToPy } from './components.js';
import { labelPos, timeline, LABEL_SIZE, fontOf, fonts, DEFAULT_FONT } from './render.js';

const n = (v) => {
  const r = Math.round(v * 10000) / 10000;
  return Number.isInteger(r) ? r.toFixed(1) : String(r);
};
const pt = ([x, y]) => `(${n(x)}, ${n(y)})`;
const str = (s) => JSON.stringify(String(s ?? ''));
const ident = (s, i) => (String(s || '').replace(/[^A-Za-z0-9]+/g, ' ').trim().split(/\s+/).map((w) => w[0].toUpperCase() + w.slice(1)).join('') || 'Lesson').replace(/^(\d)/, 'L$1') + (i ?? '');

const HELPERS = `
# Fonts: on a computer, put the lesson's .ttf files in a "fonts" folder next to
# this file (or install them). In the browser they are provided automatically.
try:
    import manimpango
    from pathlib import Path
    for _f in (Path(__file__).parent / "fonts").glob("*.[ot]tf"):
        manimpango.register_font(str(_f))
except Exception:
    pass

# --- helpers generated by Manim Visual -------------------------------------
def _pl(pts, closed=False):
    p = [np.array([x, y, 0.0]) for x, y in pts]
    if closed:
        p.append(p[0])
    m = VMobject()
    m.set_points_as_corners(p)
    return m


def _arc(cx, cy, r, a0, da):
    return Arc(radius=r, start_angle=a0, angle=da, arc_center=np.array([cx, cy, 0.0]))


def _circ(cx, cy, r):
    return Circle(radius=r, arc_center=np.array([cx, cy, 0.0]))


def _st(m, color, width, fill=None, opacity=0.0):
    m.set_stroke(color=color, width=width)
    m.set_fill(color=fill or color, opacity=opacity if fill else 0.0)
    return m


def _place(parts, x, y, rot, s):
    g = VGroup(*parts)
    g.scale(s, about_point=ORIGIN).rotate(rot * DEGREES, about_point=ORIGIN).shift([x, y, 0.0])
    return g


def _obj(body, label=None):
    """Every object is VGroup(body[, label]) so emphasis can target the body."""
    return VGroup(body, label) if label is not None else VGroup(body)


def _axes(xr, yr, w, h, color, f=None, fcolor=YELLOW, width=4):
    ax = Axes(x_range=xr, y_range=yr, x_length=w, y_length=h, tips=False,
              axis_config={"color": color, "stroke_width": 2})
    ax.shift(-(ax.c2p(xr[0], yr[0]) + ax.c2p(xr[1], yr[1])) / 2)
    parts = [ax]
    if f is not None:
        parts.append(ax.plot(f, x_range=[xr[0], xr[1]], color=fcolor, stroke_width=width))
    return parts


def _flow(m, color=YELLOW):
    return ShowPassingFlash(m[0].copy().set_stroke(color, width=8), time_width=0.5, run_time=1.5)
`;

const textStyle = (o) => `, font=${str(fontOf(o))}` + (o.bold ? ', weight=BOLD' : '') + (o.italic ? ', slant=ITALIC' : '');

function primPy(p, o) {
  const color = str(o.color);
  const sw = p.thin ? 2 : o.sw ?? 4;
  const fillArgs = (f) => (f === 'stroke' ? `, ${color}, 1.0` : f === 'shape' && (o.fo ?? 0) > 0 ? `, ${str(o.fill)}, ${n(o.fo)}` : '');
  switch (p.t) {
    case 'line': return `_st(_pl([${p.pts.map(pt).join(', ')}]), ${color}, ${n(sw)})`;
    case 'poly': return `_st(_pl([${p.pts.map(pt).join(', ')}], closed=True), ${color}, ${n(sw)}${fillArgs(p.fill)})`;
    case 'arc': return `_st(_arc(${n(p.cx)}, ${n(p.cy)}, ${n(p.r)}, ${n(p.a0)}, ${n(p.da)}), ${color}, ${n(sw)})`;
    case 'circle': return `_st(_circ(${n(p.cx)}, ${n(p.cy)}, ${n(p.r)}), ${color}, ${n(sw)}${fillArgs(p.fill)})`;
    case 'text': return `Text(${str(p.text)}, font_size=${n(p.size)}, color=${color}${textStyle(o)}).move_to([${n(p.x)}, ${n(p.y)}, 0])`;
    case 'math': return `MathTex(${str(p.text)}, font_size=${n(p.size)}, color=${color}).move_to([${n(p.x)}, ${n(p.y)}, 0])`;
  }
  return 'VMobject()';
}

export function objectPy(o) {
  const d = REG[o.type];
  if (o.type === 'group') {
    const kids = (o.children || []).map(objectPy).join(',\n        ');
    return `_obj(_place([${kids}], ${n(o.x)}, ${n(o.y)}, ${n(o.rot || 0)}, ${n(o.scale ?? 1)}))`;
  }
  let parts;
  if (o.type === 'axes') {
    const f = exprToPy(o.fx);
    parts = `_axes([${n(o.xmin)}, ${n(o.xmax)}, ${n(o.xstep)}], [${n(o.ymin)}, ${n(o.ymax)}, ${n(o.ystep)}], ${n(o.w)}, ${n(o.h)}, ${str(o.color)}` +
      (f ? `, lambda x: ${f}, ${str(o.gcolor)}, ${n(o.sw ?? 4)}` : '') + ')';
  } else {
    parts = '[' + d.prims(o).map((p) => primPy(p, o)).join(',\n            ') + ']';
  }
  const body = `_place(${parts}, ${n(o.x)}, ${n(o.y)}, ${n(o.rot || 0)}, ${n(o.scale ?? 1)})`;
  if (o.label && !d.noLabel) {
    const [lx, ly] = labelPos(o);
    return `_obj(${body},\n        Text(${str(o.label)}, font_size=${LABEL_SIZE}, color=${str(o.color)}, font=${str(fonts.lesson)}).move_to([${n(lx)}, ${n(ly)}, 0]))`;
  }
  return `_obj(${body})`;
}

const ENTER = {
  Create: (m) => `Create(${m})`, FadeIn: (m) => `FadeIn(${m})`, Write: (m) => `Write(${m})`,
  GrowFromCenter: (m) => `GrowFromCenter(${m})`, DrawBorderThenFill: (m) => `DrawBorderThenFill(${m})`,
};
const EMPH = {
  Indicate: (m) => `Indicate(${m})`, Circumscribe: (m) => `Circumscribe(${m})`, Wiggle: (m) => `Wiggle(${m})`,
  Flash: (m) => `Flash(${m}, color=YELLOW)`, FlowCurrent: (m) => `_flow(${m})`,
};

export function exportPython(project, { mode = 'slides' } = {}) {
  fonts.lesson = project.font || DEFAULT_FONT;
  const cls = ident(project.title);
  const beats = timeline(project);
  const L = [];
  const w = (s = '', ind = 2) => L.push(s ? '    '.repeat(ind) + s : '');
  L.push(`"""${String(project.title || 'Lesson').replace(/"""/g, "'''")} — generated by Manim Visual.`);
  L.push('');
  if (mode === 'slides') {
    L.push('Render and present:');
    L.push(`    manim-slides render lesson.py ${cls}`);
    L.push(`    manim-slides ${cls}                      # present`);
    L.push(`    manim-slides convert ${cls} lesson.html   # self-contained HTML slideshow`);
  } else {
    L.push('Render a video:');
    L.push(`    manim -qh lesson.py ${cls}`);
  }
  if (project.slides.some((s) => s.objects.some((o) => o.type === 'math'))) L.push('\nMath objects use MathTex and need a LaTeX installation.');
  L.push('"""');
  L.push('from manim import *');
  if (mode === 'slides') L.push('from manim_slides import Slide');
  L.push(HELPERS);
  L.push('');
  L.push(`class ${cls}(${mode === 'slides' ? 'Slide' : 'Scene'}):`);
  w('def construct(self):', 1);
  w(`self.camera.background_color = ManimColor(${str(project.bg || "#000000")})`);
  w('M = {}');
  if (mode !== 'slides') w('self.next_slide = lambda notes="": self.wait(1)');
  let lastSlide = -1, tmp = 0;
  beats.forEach((beat, bi) => {
    const slide = project.slides[beat.slide];
    if (beat.slide !== lastSlide) {
      w('');
      w(`# ---- Slide ${beat.slide + 1}: ${String(slide.name || '').replace(/\n/g, ' ')}`);
      lastSlide = beat.slide;
    }
    if (bi > 0) {
      const notes = beat.first && slide.notes ? `notes=${str(slide.notes)}` : '';
      w(`self.next_slide(${notes})`);
    } else if (mode === 'slides' && slide.notes) {
      w(`# notes: ${slide.notes.replace(/\n/g, ' ')}`);
    }
    for (const phase of beat.phases) {
      const anims = [], after = [], adds = [];
      for (const a of phase) {
        const ref = `M[${str(a.id)}]`;
        if (a.kind === 'transform') {
          const v = `_t${tmp++}`;
          w(`${v} = ${objectPy(a.to)}`);
          anims.push(`ReplacementTransform(${ref}, ${v})`);
          after.push(`${ref} = ${v}`);
        } else if (a.kind === 'fadeout') {
          anims.push(`FadeOut(${ref})`);
          after.push(`del ${ref}`);
        } else if (a.kind === 'enter') {
          w(`${ref} = ${objectPy(a.obj)}`);
          if (ENTER[a.anim]) anims.push(ENTER[a.anim](ref)); else adds.push(ref);
        } else if (a.kind === 'emph' && EMPH[a.anim]) {
          anims.push(EMPH[a.anim](ref));
        }
      }
      if (adds.length) w(`self.add(${adds.join(', ')})`);
      if (anims.length) w(`self.play(${anims.join(', ')})`);
      after.forEach((s) => w(s));
    }
  });
  w('');
  w('self.next_slide()' + (mode === 'slides' ? '' : ''));
  return L.join('\n') + '\n';
}
